with req_table as(
select o.*, p.pizza_type_id, p.size, p.price, pt.name, pt.category
from order_details as o
left join pizzas as p on o.pizza_id=p.pizza_id
left join pizza_types as pt on p.pizza_type_id=pt.pizza_type_id),

gen_rev as
(select *, sum(price*quantity) 
over (partition by category,pizza_type_id ) as per_category_type_rev
from req_table
)

select distinct(per_category_type_rev),pizza_type_id, category, tp3.drank
from(select * ,dense_rank() over (partition by category order by per_category_type_rev desc) as drank
	from gen_rev) as tp3
where tp3.drank <=3;

