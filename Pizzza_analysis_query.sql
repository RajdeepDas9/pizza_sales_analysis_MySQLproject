with req_table as
( 	select o.order_id,o.date,od.order_details_id,od.pizza_id,od.quantity, p.price   -- Cumulative rev over date, so orders table is left table
	from orders as o
    left join order_details as od on o.order_id=od.order_id
    left join pizzas as p on od.pizza_id=p.pizza_id
)

select *, sum(price*quantity) over (partition by date) as per_day_rev
from req_table ;

