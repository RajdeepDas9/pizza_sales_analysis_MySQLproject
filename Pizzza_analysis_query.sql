with cal_rev as (
select od.* ,p.price, p.pizza_type_id                                  -- Doing left join to bring in pizza price and pizz type id
from order_details as od
left join
pizzas as p
on od.pizza_id = p.pizza_id),

ptype_rev as(select pizza_type_id, sum(total_price) as type_totalp     -- Calculating revenue generated by each pizza type
from (select *, quantity*price as total_price from cal_rev) as tp      -- using cte cal_rev inside  cte ptype_rev
group by pizza_type_id),

per_contri as                                                           -- Doing cross join to add total revenue of all pizzas column
(select ptr.*, tr.*                                                     -- for making calculations easier further
from ptype_rev as ptr                                                   -- using cte ptype_rev inside cte per_contri
cross join 
(select sum(quantity * price ) as Total_revenue
from cal_rev) as tr )

select *, concat(type_totalp*100/Total_revenue,'%') as ptype_rev_contri  -- Finding contribution percentage of each pizza
from per_contri;                                                         -- type to tatal revenue


